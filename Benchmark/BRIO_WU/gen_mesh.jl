# Benchmark/BRIO_WU/gen_mesh.jl — Generate 1D Brio-Wu MHD shock tube mesh
# Usage: julia Benchmark/BRIO_WU/gen_mesh.jl
# Output: Benchmark/BRIO_WU/MESH/ directory with mesh, metrics, connectivity files
#
# Domain: x ∈ [0, 1], uniform Cartesian, single block
# Ny = Nz = 8 (quasi-1D: enough cells for 7-point reconstruction stencil)

using HDF5

# ─── Configuration ───
const NG = 4
const Nx = 800         # cells in x (800 for good shock resolution)
const Ny = 8           # quasi-1D: minimum for 7-point stencil (need ≥ 7 cells + 2*NG ghosts)
const Nz = 8           # quasi-1D: minimum for 7-point stencil
const Lx_val = 1.0     # domain length [0, 1]
const Ly_val = 8.0/Nx  # thin slab — dy = dx for isotropy
const Lz_val = 8.0/Nx  # thin slab — dz = dx for isotropy

const Nx_nodes = Nx + 1
const Ny_nodes = Ny + 1
const Nz_nodes = Nz + 1
const Nx_tot = Nx_nodes + 2*NG
const Ny_tot = Ny_nodes + 2*NG
const Nz_tot = Nz_nodes + 2*NG

println("Generating Brio-Wu 1D mesh: $(Nx)×$(Ny)×$(Nz)")

dx = FT(Lx_val / Nx)
dy = FT(Ly_val / Ny)
dz = FT(Lz_val / Nz)

# ─── Coordinate arrays (node-based, including ghost nodes) ───
x = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
y = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
z = zeros(FT, Nx_tot, Ny_tot, Nz_tot)

for k in 1:Nz_tot, j in 1:Ny_tot, i in 1:Nx_tot
    x[i, j, k] = dx * (i - NG - 1)
    y[i, j, k] = dy * (j - NG - 1)
    z[i, j, k] = dz * (k - NG - 1)
end

# ─── Metrics (Cartesian → trivial face normals and areas) ───
Areai = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nxi = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
nyi = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nzi = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
Areaj = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nxj = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
nyj = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nzj = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
Areak = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nxk = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
nyk = zeros(FT, Nx_tot, Ny_tot, Nz_tot); nzk = zeros(FT, Nx_tot, Ny_tot, Nz_tot)
Vol = zeros(FT, Nx_tot, Ny_tot, Nz_tot)

for k in 1:Nz_tot, j in 1:Ny_tot, i in 1:Nx_tot
    # ξ-faces: normal = (1, 0, 0), area = dy·dz
    if j < Ny_tot && k < Nz_tot; Areai[i,j,k] = dy*dz; nxi[i,j,k] = one(FT); end
    # η-faces: normal = (0, 1, 0), area = dx·dz
    if i < Nx_tot && k < Nz_tot; Areaj[i,j,k] = dx*dz; nyj[i,j,k] = one(FT); end
    # ζ-faces: normal = (0, 0, 1), area = dx·dy
    if i < Nx_tot && j < Ny_tot; Areak[i,j,k] = dx*dy; nzk[i,j,k] = one(FT); end
    # Cell volume (stored as 1/Vol = J in the solver)
    if i < Nx_tot && j < Ny_tot && k < Nz_tot; Vol[i,j,k] = one(FT)/(dx*dy*dz); end
end

# ─── Boundary conditions ───
# Quasi-1D Brio-Wu: outflow in x, zero-gradient in y/z
# (symmetry BC only fills 5 components, not MHD's 9)
const BC_SUPERSONIC_OUTFLOW = Int32(4)
const BC_ZERO_GRADIENT = Int32(11)
const N_BC_PARAMS_MESH = 20  # Match the updated N_BC_PARAMS in bc_types.jl

face_bc = zeros(Int32, 1, 6)
face_bc[1, 1] = BC_SUPERSONIC_OUTFLOW  # ξ- (x=0)
face_bc[1, 2] = BC_SUPERSONIC_OUTFLOW  # ξ+ (x=1)
face_bc[1, 3] = BC_ZERO_GRADIENT       # η- (y-lo, zero-gradient for quasi-1D)
face_bc[1, 4] = BC_ZERO_GRADIENT       # η+ (y-hi, zero-gradient for quasi-1D)
face_bc[1, 5] = BC_ZERO_GRADIENT       # ζ- (z-lo, zero-gradient for quasi-1D)
face_bc[1, 6] = BC_ZERO_GRADIENT       # ζ+ (z-hi, zero-gradient for quasi-1D)

bc_params = zeros(FT, 1, 6, N_BC_PARAMS_MESH)

connectivity = zeros(Int32, 1, 6)

# ─── Output ───
out_dir = joinpath(@__DIR__, "MESH")
mkpath(out_dir)

h5open(joinpath(out_dir, "block_connectivity.h5"), "w") do f
    f["Nblocks"] = Int32(1)
    f["Nx_b"] = Int32[Nx]; f["Ny_b"] = Int32[Ny]; f["Nz_b"] = Int32[Nz]
    f["face_bc"] = face_bc; f["bc_params"] = bc_params; f["connectivity"] = connectivity
end

# Store real-domain node coords only (ghost coords generated by solver)
coords = zeros(FT, 3, Nx_nodes, Ny_nodes, Nz_nodes)
coords[1,:,:,:] = x[1+NG:Nx_nodes+NG, 1+NG:Ny_nodes+NG, 1+NG:Nz_nodes+NG]
coords[2,:,:,:] = y[1+NG:Nx_nodes+NG, 1+NG:Ny_nodes+NG, 1+NG:Nz_nodes+NG]
coords[3,:,:,:] = z[1+NG:Nx_nodes+NG, 1+NG:Ny_nodes+NG, 1+NG:Nz_nodes+NG]

h5open(joinpath(out_dir, "mesh_b0.h5"), "w") do f
    f["NG"] = NG; f["Nx"] = Nx; f["Ny"] = Ny; f["Nz"] = Nz; f["coords"] = coords
    f["x"] = coords[1,:,:,:]; f["y"] = coords[2,:,:,:]; f["z"] = coords[3,:,:,:]
end

h5open(joinpath(out_dir, "metrics_b0.h5"), "w") do f
    f["Areai"]=Areai; f["nxi"]=nxi; f["nyi"]=nyi; f["nzi"]=nzi
    f["Areaj"]=Areaj; f["nxj"]=nxj; f["nyj"]=nyj; f["nzj"]=nzj
    f["Areak"]=Areak; f["nxk"]=nxk; f["nyk"]=nyk; f["nzk"]=nzk
    f["Vol"]=Vol
end

println("✓ Brio-Wu 1D mesh saved to $(out_dir)/")
println("  Nx=$(Nx), Ny=$(Ny), Nz=$(Nz), NG=$(NG)")
println("  dx=$(dx), domain=[0, $(Lx_val)]")
println("  BCs: x→outflow, y/z→symmetry")
